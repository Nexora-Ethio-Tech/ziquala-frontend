const assert = require('node:assert/strict');

// Runs inside the production-preview harness. Every request uses synthetic data.
module.exports = async ({send, evaluate, until, navigate, fulfill, origin, modes, heldContact, heldApplications, apiRequests, audit}) => {
  const set = async (selector, value) => evaluate(`(()=>{const el=document.querySelector(${JSON.stringify(selector)});if(!el)throw Error(${JSON.stringify(selector)});Object.getOwnPropertyDescriptor(el instanceof HTMLSelectElement?HTMLSelectElement.prototype:el instanceof HTMLTextAreaElement?HTMLTextAreaElement.prototype:HTMLInputElement.prototype,'value').set.call(el,${JSON.stringify(value)});el.dispatchEvent(new Event(el instanceof HTMLSelectElement?'change':'input',{bubbles:true}));})()`);
  const clickText = async text => {
    await evaluate(`Array.from(document.querySelectorAll('button')).find(b=>b.textContent.trim().toLowerCase()===${JSON.stringify(text.toLowerCase())}).click()`);
    await new Promise(resolve => setTimeout(resolve,100));
  };
  const reload = route => send('Page.navigate',{url:origin+route});
  modes.library='error';
  await reload('/elearning');
  await until("document.querySelector('[role=alert]')?.textContent.includes('library could not')",'library request failure');
  assert(!await evaluate("document.body.innerText.includes('No books added yet')"));
  await audit('functionality-library-error');
  modes.library='malformed'; await clickText('Try again');
  await until("document.querySelector('[role=alert]')?.textContent.includes('library could not')",'malformed library response');
  modes.library='ready'; await clickText('Try again');
  await until("document.body.innerText.includes('Review Book') && !document.querySelector('[role=alert]')",'library retry');
  await set('main input','unmatched synthetic query');
  await until("document.body.innerText.includes('No books match')",'library no matching search');
  await clickText('Clear Filters');
  await until("document.querySelectorAll('main article').length === 1",'clear search');
  await set('main select[aria-label="All Grades"]','Grade 1');
  await until("document.body.innerText.includes('No books match')",'grade filter');
  await clickText('Clear Filters');
  await until("document.querySelectorAll('main article').length === 1",'reset grade');
  await set('main select[aria-label="All Languages"]','Amharic');
  await until("document.body.innerText.includes('No books match')",'language filter');
  await clickText('Clear Filters');
  await until("!!document.querySelector('main article a')",'download restored');
  assert.equal(await evaluate("document.querySelector('main article a').href"),'https://drive.google.com/uc?export=download&id=fixture-book');
  await navigate('/elearning?book=unavailable-book');
  await until("document.querySelector('[role=status]')?.textContent.includes('book is unavailable')",'missing book link');
  await clickText('Continue browsing');
  await until("!location.search.includes('book=')",'dismiss missing book');
  modes.library='empty'; await reload('/elearning');
  await until("document.body.innerText.includes('No books added yet')",'genuine empty catalogue');
  modes.library='error'; await reload('/');
  await until("!!document.querySelector('main h1')",'home ready');
  await evaluate('scrollTo(0,document.body.scrollHeight)');
  await until("document.querySelector('[role=alert]')?.textContent.includes('library could not')",'featured library failure');
  modes.library='ready'; await clickText('Try again');
  await until("!!document.querySelector('a[href*=loading-check-book]')",'featured retry');

  await navigate('/monastery#donate');
  await until("!!document.querySelector('#donate button')",'donation ready');
  await evaluate("Object.defineProperty(navigator,'clipboard',{configurable:true,value:{writeText:()=>Promise.reject(Error('Fixture denied'))}});document.querySelector('#donate button').click()");
  await until("document.querySelector('#donate [role=status]').textContent.includes('manually')",'denied clipboard feedback');
  assert(await evaluate('getSelection().toString().length > 5'));
  await audit('functionality-clipboard-fallback');
  await evaluate("window.__copiedAccount='';Object.defineProperty(navigator,'clipboard',{configurable:true,value:{writeText:async text=>{window.__copiedAccount=text}}});document.querySelector('#donate button').click()");
  await until("document.querySelector('#donate [role=status]').textContent.includes('copied')",'successful clipboard feedback');
  assert(await evaluate('window.__copiedAccount === getSelection().toString()'));

  await navigate('/contact');
  await until("!!document.querySelector('main form input[name=name]')",'contact form ready');
  let start=apiRequests.filter(p=>p.endsWith('/contact')).length;
  await evaluate("document.querySelector('main form').requestSubmit()");
  assert.equal(apiRequests.filter(p=>p.endsWith('/contact')).length,start,'Invalid inquiry sent a request');
  for(const [name,value] of Object.entries({name:'  Synthetic Visitor  ',email:'visitor@example.org',phone:'+251900000000',subject:'  Fixture inquiry  ',message:'  Synthetic browser check only.  '})) await set(`main form [name=${name}]`,value);
  modes.contact='hold';
  await evaluate("document.querySelector('main form').requestSubmit();document.querySelector('main form').requestSubmit()");
  await until("document.querySelector('main form fieldset').disabled",'inquiry pending');
  for(let i=0;i<50&&!heldContact.length;i++) await new Promise(r=>setTimeout(r,100));
  assert.equal(heldContact.length,1,'Duplicate inquiry request');
  await fulfill(heldContact.shift(),{success:false},503);
  await until("!!document.querySelector('main form [role=alert]') && !document.querySelector('fieldset').disabled",'inquiry service failure');
  assert.equal(await evaluate("document.querySelector('input[name=name]').value"),'  Synthetic Visitor  ');
  await audit('functionality-contact-delivery-error');
  for(const mode of ['rate-limit','malformed','network']) {
    modes.contact=mode;
    await evaluate("document.querySelector('main form').requestSubmit()");
    await until("!!document.querySelector('main form [role=alert]') && !document.querySelector('fieldset').disabled",`inquiry ${mode}`);
    assert.equal(await evaluate("document.querySelector('input[name=email]').value"),'visitor@example.org');
  }
  modes.contact='ready';
  await evaluate("document.querySelector('main form').requestSubmit()");
  await until("!document.querySelector('main form') && !!document.querySelector('main [role=status] h3')",'inquiry confirmed success');
  await audit('functionality-contact-success');
  await evaluate("document.querySelector('main [role=status] button').click()");
  await until("document.querySelector('input[name=name]')?.value === ''",'new inquiry resets');

  await navigate('/login');
  await until("!!document.getElementById('login-identity')",'login form');
  await set('#login-identity','synthetic@example.org'); await set('#login-password','fixture-invalid-password');
  await evaluate("document.querySelector('form').requestSubmit()");
  await until("document.body.innerText.includes('Invalid credentials')",'login rejects invalid credentials');
  assert.equal(await evaluate("localStorage.getItem('ziquala_token')"),null);
  assert.equal(await evaluate('location.pathname'),'/login');

  modes.branches='empty'; await reload('/register');
  await until("document.body.textContent.includes('No campuses are available')",'empty campus guidance');
  assert.equal(await evaluate("document.querySelector('select[name=branchName]').options.length"),1);
  modes.branches='error';
  await reload('/register');
  await until("!!document.querySelector('.admissions-page form')",'admission form');
  await clickText('Next Step');
  assert.equal(await evaluate("document.querySelector('form button[type=submit]') !== null"),false,'Invalid first step advanced');
  for(const [selector,value] of Object.entries({'input[name=name]':'Synthetic Student','input[placeholder*="2010"]':'2010-01-01','select[name=gender]':'Male'})) await set(selector,value);
  await clickText('Next Step');
  assert(await evaluate("document.body.innerText.includes('Address is required') && document.querySelector('input[name=address]').getBoundingClientRect().height > 0"),'Address error hidden on another step');
  await set('input[name=address]','Fixture address');
  await clickText('Next Step');
  await until("document.querySelector('input[name=fatherName]').getBoundingClientRect().height > 0",'admission second step');
  await set('input[name=fatherName]','Synthetic Parent');
  await set('input[name=fatherPhone]','123456789');
  await clickText('Next Step');
  assert(await evaluate("document.querySelector('[role=alert]').innerText.includes('Phone must start')"),'Invalid phone error not visible');
  await audit('functionality-admission-validation');
  await set('input[name=fatherPhone]','911000000');
  await clickText('Next Step');
  assert(await evaluate("document.body.innerText.includes(\"Mother's full name is required\") && document.querySelector('input[name=motherName]').getBoundingClientRect().height > 0"),'Required parent field hidden on another step');
  await set('input[name=motherName]','Synthetic Mother');
  await clickText('Next Step');
  await until("document.querySelector('select[name=branchName]').getBoundingClientRect().height > 0",'admission third step');
  await until("!!document.querySelector('form [role=alert]')",'branch failure recovery');
  assert.equal(await evaluate("document.querySelector('select[name=branchName]').options.length"),1,'Invented fallback campuses');
  modes.branches='ready'; await clickText('Try again');
  await until("document.querySelector('select[name=branchName]').options.length === 2",'branch retry');
  assert(!await evaluate("document.body.innerText.includes('AI system will review')"));
  await audit('functionality-admission-branch-retry');
  await set('select[name=grade]','First Time'); await set('select[name=branchName]','Review Branch');
  modes.application='hold';
  await evaluate("document.querySelector('form').requestSubmit();document.querySelector('form').requestSubmit()");
  for(let i=0;i<50&&!heldApplications.length;i++) await new Promise(r=>setTimeout(r,100));
  assert.equal(heldApplications.length,1,'Duplicate admission submission');
  await fulfill(heldApplications.shift(),{success:false,error:{code:'REGISTRATION_CLOSED',message:'Registration is closed. New applications cannot be submitted at this time.'}},403);
  await until("document.body.innerText.includes('Registration is closed.')",'closure while form open');
  assert.equal(await evaluate("document.querySelector('input[name=name]').value"),'Synthetic Student');
  modes.application='malformed';
  await evaluate("document.querySelector('form').requestSubmit()");
  await until("document.body.innerText.includes('Failed to submit application')",'invalid admission response rejected');
  modes.application='ready';
  await evaluate("document.querySelector('form').requestSubmit()");
  await until("document.body.innerText.includes('Your application has been submitted successfully')",'admission confirmed submission');
  assert(!await evaluate("document.body.innerText.includes('Failed to submit application')"),'Old failure shown alongside successful admission');
  console.log('PASS functionality: library recovery/search/filters/downloads, missing books, clipboard denial/success, contact validation/duplicates/failures/success, admission campuses');
  return {libraryRecovery:true,searchAndFilters:true,downloadUrl:true,unavailableBook:true,clipboardFallback:true,contactValidation:true,contactDuplicateGuard:true,contactFailureRecovery:true,contactConfirmedSuccess:true,loginFailure:true,admissionSteps:true,admissionValidationRecovery:true,admissionCampuses:true,admissionDuplicateGuard:true,admissionClosure:true,admissionMalformedResponse:true,admissionConfirmedSuccess:true};
};
